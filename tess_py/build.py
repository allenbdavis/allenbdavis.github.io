"""Embed the tess_py/*.py modules into tess.html (between the PY_BUNDLE markers).

    python3 tess_py/build.py            # rewrite the embedded bundle
    python3 tess_py/build.py --check    # exit 1 if tess.html is out of date

The .py files are the source of truth; never edit the embedded block by hand.
The bundle is written as readable multi-line String.raw literals so git diffs
of tess.html stay line-by-line.
"""
import os, re, sys

HERE    = os.path.dirname(os.path.abspath(__file__))
HTML    = os.path.join(HERE, '..', 'tess.html')
MODULES = ['plot_utils', 'generate', 'analysis', 'plots', 'bridge']

BEGIN = '// >>> PY_BUNDLE'
END   = '// <<< PY_BUNDLE'
_ESC  = re.compile(r"`|\$\{")
_UNESC = re.compile(r"\$\{'(`|\$\{)'\}")


def js_raw(src):
    """Make Python source safe inside a JS String.raw template literal."""
    if '</script' in src.lower():
        raise ValueError('module contains "</script", which would end the page script')
    return _ESC.sub(lambda m: "${'`'}" if m.group() == '`' else "${'${'}", src)


def js_unraw(text):
    return _UNESC.sub(lambda m: m.group(1), text)


def read_module(name):
    with open(os.path.join(HERE, name + '.py'), encoding='utf-8') as f:
        return f.read().replace('\r\n', '\n')


def render_bundle():
    parts = [BEGIN + ' (generated by tess_py/build.py from tess_py/*.py -- edit those, not this block)',
             'const PY_BUNDLE = {']
    for name in MODULES:
        src = read_module(name)
        assert js_unraw(js_raw(src)) == src, f'escape round-trip failed for {name}'
        parts.append(f"'{name}': String.raw`{js_raw(src)}`,")
    parts.append('};')
    parts.append(END)
    return '\n'.join(parts)


def extract_bundle(html):
    """Return {module: source} currently embedded in the page (inverse of render)."""
    a, b = html.index(BEGIN), html.index(END)
    block = html[a:b]
    out = {}
    for m in re.finditer(r"'(\w+)': String\.raw`(.*?)`,\n(?='|\};)", block, re.S):
        out[m.group(1)] = js_unraw(m.group(2))
    return out


def build(check=False):
    with open(HTML, encoding='utf-8') as f:
        html = f.read()
    if BEGIN not in html or END not in html:
        sys.exit(f'markers not found in {HTML}')
    a = html.index(BEGIN)
    b = html.index(END) + len(END)
    new = html[:a] + render_bundle() + html[b:]
    if check:
        if new != html:
            print('tess.html is OUT OF DATE -- run: python3 tess_py/build.py')
            return 1
        print('tess.html bundle is up to date')
        return 0
    if new != html:
        with open(HTML, 'w', encoding='utf-8') as f:
            f.write(new)
        print('tess.html updated with', ', '.join(MODULES))
    else:
        print('tess.html already up to date')
    return 0


if __name__ == '__main__':
    sys.exit(build(check='--check' in sys.argv))
